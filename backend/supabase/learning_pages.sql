create table if not exists public.learning_pages (
  id bigint generated by default as identity primary key,
  slug text not null unique check (
    char_length(slug) <= 160
    and slug ~ '^[a-z0-9]+(-[a-z0-9]+)*(/[a-z0-9]+(-[a-z0-9]+)*)*$'
  ),
  category text not null check (category in ('early_learning', 'primary_school', 'secondary_school', 'fode')),
  title text not null check (char_length(title) between 3 and 160),
  eyebrow text not null default '' check (char_length(eyebrow) <= 100),
  summary text not null check (char_length(summary) between 5 and 500),
  body text not null default '' check (char_length(body) <= 10000),
  published boolean not null default false,
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, category),
  constraint learning_pages_category_path_check check (
    split_part(slug, '/', 1) = case category
      when 'early_learning' then 'early-learning'
      when 'primary_school' then 'primary-school'
      when 'secondary_school' then 'secondary-school'
      when 'fode' then 'fode'
    end
  )
);

alter table public.learning_pages enable row level security;
revoke all on public.learning_pages from anon, authenticated;
grant select on public.learning_pages to anon;
grant select, insert, update, delete on public.learning_pages to authenticated;
grant all on public.learning_pages to service_role;
revoke all on sequence public.learning_pages_id_seq from anon, authenticated;
grant usage, select on sequence public.learning_pages_id_seq to authenticated, service_role;

drop policy if exists "Public can read published learning pages" on public.learning_pages;
create policy "Public can read published learning pages" on public.learning_pages
for select to anon, authenticated using (published = true);

drop policy if exists "Admin manages learning pages" on public.learning_pages;
create policy "Admin manages learning pages" on public.learning_pages
for all to authenticated
using ((select public.is_wcc_admin()))
with check ((select public.is_wcc_admin()));

create index if not exists learning_pages_public_order_idx
on public.learning_pages (published, category, sort_order, title);

drop trigger if exists learning_pages_set_updated_at on public.learning_pages;
create trigger learning_pages_set_updated_at before update on public.learning_pages
for each row execute function public.set_updated_at();

-- Keep the four main pathways available at stable addresses.
create or replace function public.protect_learning_root()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  if old.slug in ('early-learning', 'primary-school', 'secondary-school', 'fode') then
    if tg_op = 'DELETE' then
      raise exception 'Main learning pages cannot be deleted. Unpublish the page instead.';
    end if;
    if new.slug <> old.slug or new.category <> old.category then
      raise exception 'The address and learning area of a main learning page cannot be changed.';
    end if;
  end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;
revoke all on function public.protect_learning_root() from public, anon, authenticated;
drop trigger if exists protect_learning_root on public.learning_pages;
create trigger protect_learning_root before update or delete on public.learning_pages
for each row execute function public.protect_learning_root();

